  visibleKey: visibleKey,
);

DocumentElementEntity _shape(
  String id,
  double x,
  double y,
  double width,
  double height,
  String color, {
  int z = 3,
  String? border,
  double borderWidth = 1,
  double radius = 5,
  double rotation = 0,
  String? visibleKey,
}) => DocumentElementEntity(
  id: id,
  type: DocumentElementType.shape,
  x: x,
  y: y,
  width: width,
  height: height,
  zIndex: z,
  rotation: rotation,
  visibleWhenKey: visibleKey,
  visibleWhenValue: visibleKey == null ? null : 'true',
  style: DocumentElementStyle(
    backgroundColor: color,
    borderColor: border,
    borderWidth: border == null ? 0 : borderWidth,
    shape: radius > 0
        ? DocumentElementShape.roundedRectangle
        : DocumentElementShape.rectangle,
    borderRadius: radius,
  ),
);

DocumentElementEntity _text(
  String id,
  double x,
  double y,
  double width,
  double height,
  String value,
  double size,
  String color, {
  bool bold = false,
  DocumentTextAlignment align = DocumentTextAlignment.left,
  int? maxLines = 1,
  double spacing = 0,
  String? visibleKey,
  int z = 12,
}) => DocumentElementEntity(
  id: id,
  type: DocumentElementType.text,
  x: x,
  y: y,
  width: width,
  height: height,
  zIndex: z,
  staticValue: value,
  visibleWhenKey: visibleKey,
  visibleWhenValue: visibleKey == null ? null : 'true',
  style: DocumentElementStyle(
    fontSize: size,
    fontWeight: bold ? DocumentFontWeight.bold : DocumentFontWeight.medium,
    textColor: color,
    textAlignment: align,
    verticalAlignment: DocumentVerticalAlignment.center,
    maxLines: maxLines,
    letterSpacing: spacing,
    lineHeight: 1.15,
  ),
);
