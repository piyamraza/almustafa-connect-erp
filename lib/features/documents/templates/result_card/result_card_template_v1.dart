DocumentElementEntity _panel(
  String id,
  double x,
  double y,
  double width,
  double height, {
  String? visibleKey,
}) => _shape(
  id,
  x,
  y,
  width,
  height,
  '#FFFFFF',
  z: 4,
  border: _line,
  radius: 8,
  visibleKey: visibleKey,
);

